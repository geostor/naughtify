// Honest, server-side opt-out signals and measurement helpers. Unlike the
// source-rewriting tactics, nothing here is a trick: these are the standard
// ways to tell well-behaved crawlers to stay away, plus tools to catch the
// ones that don't.

/** Known AI / scraper crawler user-agents, as of late 2025. */
export const AI_CRAWLERS = [
  "GPTBot", "ChatGPT-User", "OAI-SearchBot", // OpenAI
  "ClaudeBot", "Claude-Web", "anthropic-ai", "Claude-User", // Anthropic
  "Google-Extended", // Google (Gemini/Vertex training)
  "Applebot-Extended", // Apple
  "CCBot", // Common Crawl
  "PerplexityBot", "Perplexity-User", // Perplexity
  "Bytespider", // ByteDance
  "Amazonbot", // Amazon
  "Meta-ExternalAgent", "FacebookBot", "meta-externalagent", // Meta
  "cohere-ai", "cohere-training-data-crawler", // Cohere
  "Diffbot", "DataForSeoBot", "AI2Bot", "Ai2Bot-Dolma",
  "ImagesiftBot", "Omgilibot", "Omgili", "Timpibot", "YouBot",
  "Kangaroo Bot", "Scrapy", "magpie-crawler", "img2dataset",
  "PanguBot", "Sidetrade indexer bot", "Webzio-Extended",
];

/** A robots.txt that disallows every crawler in AI_CRAWLERS. */
export function aiCrawlerRobotsTxt(opts: { honeypotPath?: string } = {}): string {
  const blocks = AI_CRAWLERS.map((ua) => `User-agent: ${ua}\nDisallow: /`).join("\n\n");
  const trap = opts.honeypotPath
    ? `\n\n# Honeypot: no legitimate crawler should ever fetch this.\n` +
      `# Anything that does is ignoring the rules above — block it server-side.\nUser-agent: *\nDisallow: ${opts.honeypotPath}\n`
    : "";
  return `# Generated by naughtify. AI crawlers are not permitted.\n\n${blocks}${trap}\n`;
}

/** <meta> / <link> tags asking AI systems not to index or train on the page. */
export function noaiMetaTags(): string {
  return [
    `<meta name="robots" content="noai, noimageai">`,
    `<meta name="googlebot" content="noindex-ai, notrain">`,
    // TDM Reservation Protocol (EU text & data mining opt-out).
    `<meta name="tdm-reservation" content="1">`,
    `<link rel="tdm-reservation" href="#" />`,
  ].join("\n");
}

/** `X-Robots-Tag` / TDM headers for nginx and a Cloudflare Worker. */
export function xRobotsHeaders(): { nginx: string; cloudflareWorker: string } {
  const value = "noai, noimageai, notrain";
  return {
    nginx: `# In your server { } block:\nadd_header X-Robots-Tag "${value}" always;\nadd_header TDM-Reservation "1" always;`,
    cloudflareWorker:
      `// Cloudflare Worker: tag every response.\n` +
      `export default {\n` +
      `  async fetch(req, env, ctx) {\n` +
      `    const res = await fetch(req);\n` +
      `    const out = new Response(res.body, res);\n` +
      `    out.headers.set("X-Robots-Tag", "${value}");\n` +
      `    out.headers.set("TDM-Reservation", "1");\n` +
      `    return out;\n` +
      `  },\n` +
      `};`,
  };
}

/**
 * Hidden honeypot links. They're invisible to users and disallowed in
 * robots.txt, so only a misbehaving crawler follows them. Log hits on the
 * returned path(s) and block the source IP/UA.
 */
export function honeypotLinks(opts: { count?: number; basePath?: string; seed?: number } = {}): {
  html: string;
  paths: string[];
} {
  const { count = 3, basePath = "/trap" } = opts;
  let s = (opts.seed ?? 0x9e37) >>> 0;
  const slug = () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s.toString(36).padStart(6, "0").slice(0, 6);
  };
  const words = ["archive", "members", "export", "legacy", "internal", "data", "feed", "mirror"];
  const paths = Array.from({ length: count }, (_, i) => `${basePath}/${words[i % words.length]}-${slug()}`);
  const html =
    `<!-- Honeypot links: hidden from users, disallowed in robots.txt. -->\n` +
    `<div aria-hidden="true" style="position:absolute;left:-9999px;width:1px;height:1px;overflow:hidden">\n` +
    paths.map((p) => `  <a href="${p}" rel="nofollow" tabindex="-1">do not follow</a>`).join("\n") +
    `\n</div>`;
  return { html, paths };
}

/**
 * Render text at runtime instead of shipping it in the source. The page source
 * carries only base64; the real text is set as textContent after load, so
 * raw-source scrapers see noise while browsers and screen readers see the text.
 */
export function renderAtRuntime(text: string, opts: { id?: string; tag?: string } = {}): string {
  const id = opts.id ?? "n" + Math.random().toString(36).slice(2, 8);
  const tag = opts.tag ?? "span";
  const b64 = Buffer.from(text, "utf8").toString("base64");
  return (
    `<${tag} id="${id}"></${tag}>\n` +
    `<script>(function(){var e=document.getElementById(${JSON.stringify(id)});` +
    `if(e)e.textContent=decodeURIComponent(escape(atob(${JSON.stringify(b64)})));})();</script>`
  );
}

/**
 * A tiny client beacon that reports when your canary string appears where it
 * shouldn't. Drop it on a page; if the page is re-served by a scraper that
 * rewrites URLs, the beacon fires to your endpoint with the current location.
 */
export function canaryBeacon(canaryId: string, endpoint: string): string {
  return (
    `<script>(function(){try{` +
    `var c=${JSON.stringify(canaryId)},u=${JSON.stringify(endpoint)};` +
    `if(location.hostname!==document.currentScript.dataset.host){` +
    `navigator.sendBeacon(u,JSON.stringify({canary:c,at:location.href,ref:document.referrer}));}` +
    `}catch(e){}})();</script>`
  );
}
